// Writes the native play scripts (tests/native/*.play) from the rules: each
// chamber's build is planned by simulating the browser build's session in
// node (src/session.js, the same fixed-step physics the engine runs), so a
// script only presses keys and taps that end in the outcome it waits for.
//   journey-keys.play   desktop: Journey chambers 1–4 by keys (material digit, cursor arrows,
//                       Enter, R), each to its results and the next chamber
//   learn-phone.play    phone (390 × 844, DPR 3): the six lessons by finger on the tray and the
//                       bodies' named targets (pin and spring joints, delete), each to its results
//   challenge-land.play phone sideways (844 × 390, DPR 3): Speedrun Bay, paused and resumed, run
//   menus.play          desktop: how to play, leaderboards, modes and setups, progression, a
//                       chamber's pause, settings and help panels
//   node tools/gen-plays.mjs
import { writeFileSync, mkdirSync } from 'node:fs';
import { CHALLENGE_LEVELS, JOURNEY_LEVELS, LEARN_LESSONS } from '../src/content.js';
import { CHAMBER } from '../src/rules.js';
import { createGameSession } from '../src/session.js';

const OUT = new URL('../tests/native/', import.meta.url);
mkdirSync(OUT, { recursive: true });
const START = { x: CHAMBER.w / 2, y: CHAMBER.h * 0.6 };
const clamp = (v, lo, hi) => Math.max(lo, Math.min(hi, v));

/** Plays a plan ({ spawns: [{ material, dx, dy }] }) as main.ts does; the terminal phase. */
function simulate(level, plan) {
  const s = createGameSession({ level, seed: level.seed, mode: level.mode });
  const cur = { ...START };
  for (const sp of plan.spawns) {
    cur.x = clamp(cur.x + sp.dx * 0.5, 0.5, CHAMBER.w - 0.5);
    cur.y = clamp(cur.y + sp.dy * 0.5, 0.5, CHAMBER.h - 0.5);
    const r = s.dispatch({ type: 'spawn', material: sp.material, x: Math.round(cur.x * 4) / 4, y: Math.round(cur.y * 4) / 4 });
    if (r.error) return 'illegal';
  }
  s.dispatch({ type: 'run' });
  let n = 0;
  while (s.state.phase === 'run' && n++ < 20000) s.step(1);
  return s.state.phase;
}
/** Run alone, else one spawn anywhere the cursor reaches (nearest the start first). */
function solve(level) {
  if (simulate(level, { spawns: [] }) === 'won') return { spawns: [] };
  const cands = [];
  for (let dx = -19; dx <= 19; dx++) for (let dy = -13; dy <= 9; dy++) cands.push([dx, dy]);
  cands.sort((a, b) => Math.abs(a[0]) + Math.abs(a[1]) - Math.abs(b[0]) - Math.abs(b[1]));
  for (const [dx, dy] of cands) for (const material of level.allowedMaterials) {
    const plan = { spawns: [{ material, dx, dy }] };
    if (simulate(level, plan) === 'won') return plan;
  }
  return null;
}
function keysFor(level, plan) {
  const out = [];
  for (const sp of plan.spawns) {
    out.push(`key Digit${level.allowedMaterials.indexOf(sp.material) + 1} 1`, 'frames 2');
    const h = sp.dx < 0 ? 'ArrowLeft' : 'ArrowRight', v = sp.dy < 0 ? 'ArrowDown' : 'ArrowUp';
    for (let i = 0; i < Math.abs(sp.dx); i++) out.push(`key ${h} 1`, 'frames 1');
    for (let i = 0; i < Math.abs(sp.dy); i++) out.push(`key ${v} 1`, 'frames 1');
    out.push('key Enter 1', 'frames 3');
  }
  out.push('key KeyR 1');
  return out;
}

// ---------------------------------------------------------------- Journey 1–6 by keys (desktop)
{
  const lines = [
    '# Generated by tools/gen-plays.mjs: Journey chambers 1-4 on a desktop (1280 x 800) by keys, each planned',
    '# from the rules (a material digit, cursor arrows, Enter, R) and played to its results.',
    '# viewport 1280x800@1',
    'until 600 Daily challenge', 'frames 10', 'click =Play',
  ];
  for (let i = 0; i < 4; i++) {
    const level = JOURNEY_LEVELS[i];
    const plan = solve(level);
    if (!plan) throw new Error(`no plan for ${level.id}`);
    lines.push(`# ${level.id} ${level.name}: ${plan.spawns.map((s) => `${s.material} at cursor ${s.dx},${s.dy}`).join(', ') || 'run'}`);
    lines.push('until 300 Spawns left', 'frames 30');
    if (i === 0) lines.push('save journey-1');
    lines.push(...keysFor(level, plan));
    if (i === 1) lines.push('frames 40', 'save journey-2-run');
    lines.push('until 2400 Score breakdown', 'expect Delivery complete', 'frames 10');
    if (i === 0) lines.push('save journey-1-results');
    if (i < 3) lines.push('click =Next chamber');
  }
  lines.push('click =Modes', 'until 120 Choose a mode', 'frames 5');
  writeFileSync(new URL('journey-keys.play', OUT), lines.join('\n') + '\n');
}

// ---------------------------------------------------------------- the six lessons by touch (phone)
{
  const lines = [
    '# Generated by tools/gen-plays.mjs: the six Learn lessons on a phone (390 x 844, DPR 3) by finger: the tray',
    "# buttons and the bodies' named targets (joints by two taps, delete after a tap), each run to its results.",
    '# viewport 390x844@3',
    'until 600 Daily challenge', 'frames 10', 'touch =All modes', 'until 120 Choose a mode', 'frames 10', 'touch =Learn',
  ];
  const touch = (t) => [`touch =${t}`, 'frames 8'];
  const name = { wood: 'Wood', steel: 'Steel', glass: 'Glass', rubber: 'Rubber' };
  LEARN_LESSONS.forEach((l, i) => {
    lines.push(`# ${l.id} ${l.name}`, 'until 300 Spawns left', 'frames 30');
    if (i === 0) lines.push('save lesson-1');
    const mat = (m) => `${name[m]} (${l.allowedMaterials.indexOf(m) + 1})`;
    const sim = createGameSession({ level: l, seed: l.seed, mode: l.mode });
    const spawn = (m) => { lines.push(...touch(mat(m)), ...touch('Spawn at cursor (Enter)')); sim.dispatch({ type: 'spawn', material: m, x: 10, y: 7.25 }); };
    let balls = 0;
    for (const st of l.steps) {
      const r = st.requireCommand;
      if (r.type === 'spawn') { spawn(r.material ?? l.allowedMaterials[0]); balls++; }
      else if (r.type === 'joint') {
        const j = r.joint === 'pin' ? 'Pin Joint (J)' : 'Spring (J)';
        const p = l.payloads[0];
        const first = sim.state.bodies.find((b) => b.kind === 'player');
        lines.push(...touch(j), ...touch(`${name[p.material]} payload 1`), ...touch(`${name[first.material]} ball 1`));
        if (i === 2) lines.push('frames 20', 'save lesson-3-joint');
        sim.dispatch({ type: 'joint', joint: r.joint, a: 'p0', b: first.id });
      } else if (r.type === 'delete') {
        const b = sim.state.bodies.find((x) => x.kind === 'player');
        lines.push(...touch(`${name[b.material]} ball 1`), ...touch('Delete selected (Del)'));
        sim.dispatch({ type: 'delete', target: b.id });
      }
    }
    if (!l.steps.some((s) => s.requireCommand.type === 'run')) lines.push('expect Lesson complete');
    lines.push(...touch('Run (R)'));
    sim.dispatch({ type: 'run' });
    while (sim.state.phase === 'run') sim.step(1);
    lines.push(`# simulated: ${sim.state.phase}`);
    lines.push('until 2400 Score breakdown', `expect ${sim.state.phase === 'won' ? 'Delivery complete' : 'Run failed'}`, 'frames 10');
    if (i === 0) lines.push('save lesson-1-results');
    if (i < LEARN_LESSONS.length - 1) lines.push('touch =Next lesson');
  });
  writeFileSync(new URL('learn-phone.play', OUT), lines.join('\n') + '\n');
}

// ---------------------------------------------------------------- Speedrun Bay sideways
{
  const level = CHALLENGE_LEVELS[1];
  const plan = solve(level);
  if (!plan) throw new Error('no plan for challenge-2');
  const lines = [
    '# Generated by tools/gen-plays.mjs: the Speedrun Bay challenge on a phone held sideways (844 x 390, DPR 3):',
    '# the setup panel, the chamber, the pause panel and back, then the planned build run to its results.',
    '# viewport 844x390@3',
    'until 600 Daily challenge', 'frames 10', 'touch =All modes', 'until 120 Choose a mode', 'frames 10',
    'touch =Challenge', 'frames 10', 'save challenge-setup', 'touch =Speedrun Bay', 'until 300 Spawns left', 'frames 30',
    'save challenge-2', 'touch =Pause (Esc)', 'until 60 Restart chamber', 'frames 10', 'save challenge-pause', 'touch =Resume', 'frames 10',
  ];
  const name = { wood: 'Wood', steel: 'Steel', rubber: 'Rubber' };
  for (const sp of plan.spawns) {
    lines.push(`touch =${name[sp.material]} (${level.allowedMaterials.indexOf(sp.material) + 1})`, 'frames 5');
    for (let i = 0; i < Math.abs(sp.dx); i++) lines.push(`touch =${sp.dx < 0 ? '←' : '→'}`, 'frames 3');
    for (let i = 0; i < Math.abs(sp.dy); i++) lines.push(`touch =${sp.dy < 0 ? '↓' : '↑'}`, 'frames 3');
    lines.push('touch =Spawn at cursor (Enter)', 'frames 5');
  }
  lines.push('touch =Run (R)', 'frames 30', 'save challenge-2-run', 'until 1200 Score breakdown', 'expect Delivery complete', 'frames 10', 'save challenge-results');
  writeFileSync(new URL('challenge-land.play', OUT), lines.join('\n') + '\n');
}
